#!/bin/bash
#
# common.sh - 颜色定义和日志函数
#
# 此文件提供了通用的日志输出和颜色定义功能，被其他所有脚本依赖。
# 使用方式: source "$SCRIPT_DIR/lib/common.sh"
#

# 防止重复加载（使用 guard 变量避免多次 source 导致的问题）
[[ -n "${_COMMON_SH_LOADED:-}" ]] && return 0
_COMMON_SH_LOADED=1

# =============================================================================
# 颜色定义 - ANSI 转义码
# =============================================================================
RED='\033[0;31m'      # 红色 - 用于错误信息
GREEN='\033[0;32m'    # 绿色 - 用于成功信息
YELLOW='\033[1;33m'   # 黄色 - 用于警告信息
BLUE='\033[0;34m'     # 蓝色 - 用于普通日志
CYAN='\033[0;36m'     # 青色 - 用于调试信息
NC='\033[0m'          # No Color - 重置颜色

# =============================================================================
# 日志函数
# 所有日志输出到 stderr，避免与函数返回值（stdout）混淆
# =============================================================================

# 输出普通信息日志
# 参数: $1 - 日志内容
log() { echo -e "${BLUE}[INFO]${NC} $1" >&2; }

# 输出成功日志
# 参数: $1 - 日志内容
log_success() { echo -e "${GREEN}[SUCCESS]${NC} $1" >&2; }

# 输出警告日志
# 参数: $1 - 日志内容
log_warn() { echo -e "${YELLOW}[WARN]${NC} $1" >&2; }

# 输出错误日志
# 参数: $1 - 日志内容
log_error() { echo -e "${RED}[ERROR]${NC} $1" >&2; }

# 输出调试日志（仅在 OPT_VERBOSE=true 时显示）
# 参数: $1 - 日志内容
log_debug() {
    if [[ "${OPT_VERBOSE:-false}" == true ]]; then
        echo -e "${CYAN}[DEBUG]${NC} $1" >&2
    fi
}

# 输出错误日志并退出脚本
# 参数: $1 - 错误信息
error() { log_error "$1"; exit 1; }
